"""Build a native macOS .app and ZIP, preserving earlier build outputs."""
from __future__ import annotations

from datetime import datetime, timezone
import hashlib
import importlib.metadata as metadata
import json
import os
from pathlib import Path
import platform
import shutil
import subprocess
import sys
import uuid

ROOT = Path(__file__).resolve().parents[1]


def sha256(path: Path) -> str:
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def checked_output(args: list[str]) -> str:
    return subprocess.run(args, capture_output=True, text=True, check=True).stdout


def find_tools(architecture: str) -> dict[str, Path]:
    tools = {}
    for name in ("ffmpeg", "ffprobe"):
        candidate = ROOT / "tools" / name
        found = str(candidate) if candidate.is_file() else shutil.which(name)
        if not found:
            raise SystemExit(f"缺少 {name}，请先运行 brew install ffmpeg。")
        path = Path(found).resolve()
        arches = checked_output(["/usr/bin/lipo", "-archs", str(path)]).split()
        if architecture not in arches:
            raise SystemExit(f"{name} 的架构 {arches} 与 Python 的 {architecture} 不一致。")
        tools[name] = path
    devices = checked_output([str(tools["ffmpeg"]), "-hide_banner", "-devices"])
    encoders = checked_output([str(tools["ffmpeg"]), "-hide_banner", "-encoders"])
    if "avfoundation" not in devices:
        raise SystemExit("FFmpeg 未包含 macOS avfoundation 采集设备。")
    for encoder in ("libx264", "libx265", "libmp3lame", "aac"):
        if encoder not in encoders:
            raise SystemExit(f"FFmpeg 缺少 {encoder} 编码器。")
    return tools


def spec_source(work: Path, tools: dict[str, Path], version: str,
                minimum_macos: str = "15.0") -> str:
    """Let PyInstaller collect and relocate FFmpeg's dependent dylibs as well."""
    plist = {
        "CFBundleDisplayName": "土豆工厂",
        "CFBundleShortVersionString": version,
        "CFBundleVersion": version,
        "LSMinimumSystemVersion": minimum_macos,
        "NSHighResolutionCapable": True,
        "NSMicrophoneUsageDescription": "录制系统声音、麦克风及讲解音轨。",
        "NSCameraUsageDescription": "通过 AVFoundation 采集屏幕画面。",
    }
    return f"""# Generated by scripts/build_macos.py
from PyInstaller.utils.hooks import collect_all
datas, binaries, hiddenimports = collect_all('soundcard')
binaries += {[(str(path), '.') for path in tools.values()]!r}
datas += {[(str(ROOT / 'docs'), 'docs'), (str(work / 'licenses'), 'licenses'),
           (str(ROOT / 'THIRD_PARTY_NOTICES.md'), '.')]!r}
a = Analysis([{str(ROOT / 'app.py')!r}], pathex=[{str(ROOT)!r}],
             binaries=binaries, datas=datas,
             hiddenimports=hiddenimports + ['lameenc', 'macos_capture'],
             excludes=['torch', 'tensorflow', 'jax', 'cupy', 'matplotlib', 'IPython', 'pytest'])
pyz = PYZ(a.pure)
exe = EXE(pyz, a.scripts, [], exclude_binaries=True, name='PotatoFactory',
          console=False, argv_emulation=False, codesign_identity=None)
coll = COLLECT(exe, a.binaries, a.datas, name='PotatoFactory')
app = BUNDLE(coll, name='PotatoFactory.app', icon={str(work / 'studio.icns')!r},
             bundle_identifier='com.ryango3.potatofactory', info_plist={plist!r})
"""


def collect_licenses(destination: Path) -> None:
    shutil.copytree(ROOT / "licenses", destination)
    # Add the actual macOS wheels' notices, alongside the repository notices.
    for dist in metadata.distributions():
        name = dist.metadata.get("Name", "")
        safe_name = "".join(c for c in name if c.isalnum() or c in "._-")
        if not safe_name:
            continue
        for entry in dist.files or []:
            relative = Path(str(entry))
            if (".." in relative.parts or relative.is_absolute()
                    or not any(word in str(relative).lower()
                               for word in ("license", "copying", "notice"))):
                continue
            source = Path(dist.locate_file(entry))
            if source.is_file():
                target = destination / "macos-wheels" / safe_name / relative
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(source, target)


def main() -> None:
    if sys.platform != "darwin":
        raise SystemExit("macOS .app 必须在 Mac 上构建；Windows 不支持交叉打包。")
    architecture = platform.machine().lower()
    if architecture not in {"arm64", "x86_64"}:
        raise SystemExit(f"不支持的 Mac 架构：{architecture}")
    macos_major = int(platform.mac_ver()[0].split(".")[0])
    if macos_major < 15:
        raise SystemExit("当前 macOS 构建流程需要 macOS 15 或更新版本。")
    minimum_macos = f"{macos_major}.0"
    import tkinter
    from PIL import Image
    # Fail early if Python lacks Tcl/Tk or the icon cannot be read.
    print(f"Python {sys.version.split()[0]} / Tcl/Tk {tkinter.TkVersion} / {architecture}")
    tools = find_tools(architecture)
    version = (ROOT / "VERSION").read_text(encoding="utf-8").strip()
    build_id = datetime.now().strftime("%Y%m%d_%H%M%S") + "_" + uuid.uuid4().hex[:8]
    work = ROOT / "builds" / build_id
    release = ROOT / "releases" / build_id
    bundle_name = f"PotatoFactory-v{version}-macos-{architecture}"
    bundle = release / bundle_name
    work.mkdir(parents=True, exist_ok=False)
    bundle.mkdir(parents=True, exist_ok=False)
    with Image.open(ROOT / "assets" / "studio.ico") as icon:
        icon.convert("RGBA").resize((1024, 1024)).save(work / "studio.icns", format="ICNS")
    collect_licenses(work / "licenses")
    spec = work / "PotatoFactory.spec"
    spec.write_text(spec_source(work, tools, version, minimum_macos), encoding="utf-8")
    subprocess.run([
        sys.executable, "-m", "PyInstaller", "--noconfirm",
        "--distpath", str(work / "dist"), "--workpath", str(work / "work"), str(spec),
    ], cwd=ROOT, check=True)
    app = bundle / "PotatoFactory.app"
    shutil.copytree(work / "dist" / "PotatoFactory.app", app, symlinks=True)
    # PyInstaller applies an ad-hoc signature after relocating native libraries.
    subprocess.run(["/usr/bin/codesign", "--verify", "--deep", "--strict", str(app)], check=True)
    subprocess.run([str(app / "Contents" / "MacOS" / "PotatoFactory"), "--smoke-test"],
                   cwd=work, check=True, timeout=120)
    shutil.copy2(ROOT / "docs" / "MACOS_USER_GUIDE.md", bundle / "macOS使用说明.md")
    shutil.copy2(ROOT / "docs" / "MACOS_QUICK_START.md", bundle / "macOS简易说明.txt")
    (bundle / "README.txt").write_text(
        "土豆工厂 · macOS 实验版\n作者：大土豆|Ryan\n\n"
        "将 PotatoFactory.app 拖到“应用程序”后打开，无需安装 Python 或 FFmpeg。\n"
        "首次打开可能需要在“隐私与安全性”中允许打开，并授权屏幕录制、麦克风。\n"
        "此包为临时签名，尚未通过 Apple Developer ID 签名和公证。\n"
        f"系统要求：macOS {minimum_macos} 或更新版本，{architecture}。\n"
        "系统声音需另行安装 BlackHole 2ch 并配置多输出设备。\n"
        "先看 macOS简易说明.txt；详细设置见 macOS使用说明.md。\n"
        "仅支持主显示器，Retina 录像按逻辑分辨率导出。\n"
        "需要在实际 Mac 上验收录屏、声音和暂停同步后再正式分发。\n",
        encoding="utf-8")
    from build import SOURCES
    git = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True,
                         text=True) if shutil.which("git") else None
    info = {
        "app_name": "土豆工厂", "author": "大土豆|Ryan", "version": version,
        "build_id": build_id, "target_platform": f"macos-{architecture}",
        "minimum_macos": minimum_macos,
        "built_at_utc": datetime.now(timezone.utc).isoformat(),
        "python": sys.version, "platform": platform.platform(),
        "git_commit": git.stdout.strip() if git and git.returncode == 0 else None,
        "source_sha256": {name: sha256(ROOT / name) for name in SOURCES},
        "dependencies": {d.metadata["Name"]: d.version for d in metadata.distributions()
                         if d.metadata.get("Name")},
        "tools": {name: {"sha256": sha256(path),
                          "version": checked_output([str(path), "-version"])}
                  for name, path in tools.items()},
        "signing": "ad-hoc; not notarized",
        "validation": "bundled GUI and FFmpeg smoke test; real recording requires manual acceptance",
    }
    (bundle / "build-info.json").write_text(
        json.dumps(info, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (bundle / "SHA256SUMS.txt").write_text(
        "".join(f"{sha256(path)}  {path.relative_to(bundle).as_posix()}\n"
                for path in sorted(bundle.rglob("*")) if path.is_file()), encoding="utf-8")
    archive = release / (bundle_name + ".zip")
    # ditto preserves executable bits and PyInstaller's macOS framework symlinks.
    subprocess.run(["/usr/bin/ditto", "-c", "-k", "--sequesterRsrc", "--keepParent",
                    str(bundle), str(archive)], check=True)
    result = {"bundle": str(bundle), "archive": str(archive), "sha256": sha256(archive)}
    (release / "build-result.json").write_text(
        json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(result, ensure_ascii=False))


if __name__ == "__main__":
    main()
